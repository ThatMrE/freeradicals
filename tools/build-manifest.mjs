#!/usr/bin/env node
/**
 * Writes the development manifest (the repo root doubles as the unpacked
 * extension) and the two generated content-script tables.
 *
 * The manifest itself is defined once, in tools/targets.mjs, and shared with
 * the store builder — so the tree you load unpacked and the tree that ships
 * cannot drift apart.
 *
 *   node tools/build-manifest.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import { PLATFORMS } from '../core/platforms.js';
import { buildManifest, hostMatches } from './targets.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

writeFileSync(
  join(root, 'manifest.json'),
  `${JSON.stringify(buildManifest({ target: 'chrome', version }), null, 2)}\n`,
);

/* --- routes.generated.js: lets boot.js pre-hide before core loads ---------- */
const routeTable = PLATFORMS.map((p) => ({
  id: p.id,
  hosts: p.web.hosts,
  feedRoutes: p.web.feedRoutes.map((re) => re.source),
}));

writeFileSync(
  join(root, 'extension/content/routes.generated.js'),
  `/* GENERATED by tools/build-manifest.mjs — do not edit. Source: core/platforms.js */
globalThis.__FR_ROUTES__ = ${JSON.stringify(routeTable, null, 2)};
`,
);

/* --- signals.generated.js: the MAIN-world probe cannot import modules ------ */
const signalTable = PLATFORMS.map((p) => ({
  id: p.id,
  hosts: p.web.hosts,
  signals: (p.web.publishSignals || []).map((s) => ({
    method: s.method || null,
    url: s.url ? s.url.source : null,
    urlFlags: s.url ? s.url.flags : '',
    body: s.body ? s.body.source : null,
    bodyFlags: s.body ? s.body.flags : '',
  })),
}));

writeFileSync(
  join(root, 'extension/content/signals.generated.js'),
  `/* GENERATED by tools/build-manifest.mjs — do not edit. Source: core/platforms.js */
globalThis.__FR_SIGNALS__ = ${JSON.stringify(signalTable, null, 2)};
`,
);

console.log(
  `manifest.json + generated tables written for ${PLATFORMS.length} platforms `
  + `(${hostMatches().length} match patterns)`,
);
